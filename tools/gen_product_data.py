#!/usr/bin/env python3
"""Copy each arm's shipped profile, URDF and Star leader mapping from its Python SDK into its TypeScript package.

    ~/maker-arm-sdk/.venv/bin/python tools/gen_product_data.py            # write
    ~/maker-arm-sdk/.venv/bin/python tools/gen_product_data.py --check    # exit 1 if a file is stale

MAKER_ARM_SDK_DIR and METAL_ARM_SDK_DIR name other checkouts of the SDKs (default ~/maker-arm-sdk, ~/metal-arm-sdk).

The Python SDK repos are the source; the generated files are never edited by hand.
"""

import argparse
import json
import os
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
HOME = Path.home()
MAKER_SDK = Path(os.environ.get("MAKER_ARM_SDK_DIR", HOME / "maker-arm-sdk"))
METAL_SDK = Path(os.environ.get("METAL_ARM_SDK_DIR", HOME / "metal-arm-sdk"))
PRODUCTS = {
    "maker-arm": (MAKER_SDK / "maker_arm", "maker_arm_v1.yaml", "star_to_maker_v1.json"),
    "metal-arm": (METAL_SDK / "metal_arm", "metal_arm_v1.yaml", "star_to_metal_v1.json"),
}
HEADER = "// Generated by tools/gen_product_data.py from the Python SDK. Do not edit.\n"


def outputs(package_dir: Path, profile_name: str, mapping_name: str) -> dict[str, str]:
    raw = yaml.safe_load((package_dir / "profiles" / profile_name).read_text())
    urdf = (package_dir / raw.pop("urdf")).read_text()
    profile = (HEADER + 'import type { RawProfile } from "@makermods/arm-core";\n\n'
               f"/** {profile_name}, without its `urdf` entry (see urdf.ts). */\n"
               f"export const PROFILE: RawProfile = {json.dumps(raw, indent=2)};\n")
    text = HEADER + f"\nexport const URDF: string = {json.dumps(urdf)};\n"
    mapping = json.loads((package_dir / "profiles" / mapping_name).read_text())
    star = (HEADER + f"\n/** {mapping_name}: the Star Arm 102 leader mapping onto this arm (a StarMapping). */\n"
            f"export const STAR_MAPPING = {json.dumps(mapping, indent=2)};\n")
    return {"profile.ts": profile, "urdf.ts": text, "star-mapping.ts": star}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for package, (package_dir, profile_name, mapping_name) in PRODUCTS.items():
        out_dir = ROOT / "packages" / package / "src" / "generated"
        for name, content in outputs(package_dir, profile_name, mapping_name).items():
            path = out_dir / name
            if a.check:
                if not path.exists() or path.read_text() != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                out_dir.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
                print("wrote", path.relative_to(ROOT))
    if stale:
        print("stale:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
